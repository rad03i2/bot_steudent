"""أدوات مساعدة للنصوص العربية: التطبيع، أسماء الأيام والأشهر، والأرقام."""

from __future__ import annotations

import re

# تشكيل وحروف زائدة
_DIACRITICS = re.compile(r"[ؐ-ًؚ-ٰٟۖ-ۭـ]")
_ARABIC_DIGITS = str.maketrans("٠١٢٣٤٥٦٧٨٩۰۱۲۳۴۵۶۷۸۹", "01234567890123456789")


def normalize(text: str) -> str:
    """تطبيع النص العربي ليسهل مطابقته: يوحّد الألفات والياء والتاء المربوطة،
    ويحذف التشكيل والتطويل، ويحوّل الأرقام العربية الهندية إلى لاتينية."""
    text = text.translate(_ARABIC_DIGITS)
    text = _DIACRITICS.sub("", text)
    text = re.sub("[إأآٱ]", "ا", text)
    text = text.replace("ى", "ي").replace("ة", "ه").replace("ؤ", "و").replace("ئ", "ي")
    text = re.sub(r"[،,؛;؟?!.:\"'()\[\]{}«»]", " ", text)
    text = re.sub(r"\s+", " ", text)
    return text.strip().lower()


# أيام الأسبوع: الأرقام حسب datetime.weekday() (الاثنين = 0)
WEEKDAY_NAMES_AR = ["الاثنين", "الثلاثاء", "الأربعاء", "الخميس", "الجمعة", "السبت", "الأحد"]

